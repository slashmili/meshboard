import { test, expect } from '@playwright/test'
test('undo controls and keyboard restore a group move and remain reachable on phones', async ({ page }) => {
  await page.goto('/')
  const undo = page.getByRole('button', { name: 'Undo', exact: true })
  const redo = page.getByRole('button', { name: 'Redo', exact: true })
  const objects = page.getByTestId('drawing-elements').locator('rect')
  await expect(undo).toBeDisabled(); await expect(redo).toBeDisabled()
  await page.keyboard.press('r')
  for (const x of [400,600]) {
    await page.mouse.move(x,300); await page.mouse.down(); await page.mouse.move(x+60,360); await page.mouse.up()
  }
  const positions = () => objects.evaluateAll(nodes => nodes.map(n => n.getAttribute('x')))
  const before = await positions()
  await page.keyboard.press('v')
  await page.mouse.move(350,250); await page.mouse.down(); await page.mouse.move(700,410); await page.mouse.up()
  await page.mouse.move(430,330); await page.mouse.down(); await page.mouse.move(530,430); await page.mouse.up()
  const moved = await positions(); expect(moved).not.toEqual(before)
  await undo.click(); expect(await positions()).toEqual(before)
  await page.keyboard.press('Control+Shift+z'); expect(await positions()).toEqual(moved)
  await page.keyboard.press('Control+z'); expect(await positions()).toEqual(before)
  await redo.click(); expect(await positions()).toEqual(moved)
  await page.keyboard.press('t'); await page.mouse.click(800,500)
  await page.getByLabel('Text', {exact:true}).fill('Draft')
  await page.keyboard.press('Control+z')
  expect(await positions()).toEqual(moved)
  await page.getByRole('button', {name:'Cancel', exact:true}).click()
  await page.setViewportSize({ width:390, height:844 })
  await expect(undo).toBeInViewport(); await expect(redo).toBeInViewport()
})
