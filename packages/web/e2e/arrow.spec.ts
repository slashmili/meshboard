import { test, expect } from '@playwright/test'

test('arrows have two wings, snap with Shift and can be erased by the head', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Arrow (A)', exact: true }).click()
  await page.mouse.move(350, 300); await page.mouse.down()
  await page.mouse.move(550, 300); await page.mouse.up()
  const arrow = page.getByTestId('drawing-elements').locator('[data-element-type="arrow"]')
  await expect(arrow).toHaveCount(1)
  const points = (await arrow.getAttribute('points'))!.split(' ').map(p => p.split(',').map(Number))
  expect(points).toHaveLength(5)
  expect(points[1]).toEqual(points[3])
  expect(points[2][1]).toBeGreaterThan(points[1][1])
  expect(points[4][1]).toBeLessThan(points[1][1])
  await page.keyboard.press('e'); await page.mouse.click(545, 303)
  await expect(arrow).toHaveCount(0)
  await page.keyboard.press('a'); await page.keyboard.down('Shift')
  await page.mouse.move(350, 300); await page.mouse.down()
  await page.mouse.move(550, 480); await page.mouse.up(); await page.keyboard.up('Shift')
  const snapped = (await arrow.getAttribute('points'))!.split(' ').map(p => p.split(',').map(Number))
  expect(snapped[1][0] - snapped[0][0]).toBeCloseTo(snapped[1][1] - snapped[0][1])
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('button', { name: 'Arrow (A)', exact: true })).toBeInViewport()
  await expect(page.getByRole('button', { name: 'Pan (H)', exact: true })).toBeInViewport()
})
