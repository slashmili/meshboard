import { test, expect } from '@playwright/test'

test('text and notes can be created, edited, canceled and erased without interpreting markup', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Text (T)', exact: true }).click()
  await page.mouse.click(400, 300)
  await page.getByLabel('Text', { exact: true }).fill('Hello <script>alert(1)</script>\n世界 👋')
  await page.getByRole('button', { name: 'Save text', exact: true }).click()
  const objects = page.getByTestId('drawing-elements').locator(':scope > *')
  await expect(objects).toHaveCount(1)
  await expect(objects.first()).toContainText('<script>')
  await expect(page.locator('svg script')).toHaveCount(0)
  await page.mouse.click(420, 320)
  await page.getByLabel('Text', { exact: true }).fill('Edited box')
  await page.getByRole('button', { name: 'Save text', exact: true }).click()
  await expect(objects).toHaveCount(1)
  await expect(objects.first()).toHaveText('Edited box')
  await page.keyboard.press('n')
  await page.mouse.click(750, 300)
  await page.getByLabel('Text', { exact: true }).fill('A sticky note')
  await page.getByRole('button', { name: 'Save text', exact: true }).click()
  await expect(objects).toHaveCount(2)
  await expect(page.locator('[data-element-type="sticky"] rect')).toHaveAttribute('fill', '#fff0a8')
  await page.mouse.click(750, 500)
  await page.getByLabel('Text', { exact: true }).fill('Cancel me')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(objects).toHaveCount(2)
  await page.screenshot({ path: testInfo.outputPath('text-notes.png') })
  await page.keyboard.press('e')
  await page.mouse.click(800, 330)
  await expect(objects).toHaveCount(1)
})

test('notes work on a narrow touch layout', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true })
  try {
    const page = await context.newPage()
    await page.goto('http://127.0.0.1:5173/')
    await page.getByRole('button', { name: 'Sticky note (N)' }).tap()
    const cdp = await context.newCDPSession(page)
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ id: 0, x: 140, y: 500 }, { id: 1, x: 240, y: 500 }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ id: 0, x: 90, y: 500 }, { id: 1, x: 290, y: 500 }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect(page.getByRole('dialog')).not.toBeVisible()
    await expect(page.getByTestId('drawing-elements').locator(':scope > *')).toHaveCount(0)
    await page.getByRole('button', { name: 'Reset view' }).tap()
    await page.touchscreen.tap(55, 320)
    await page.getByLabel('Text', { exact: true }).fill('Touch note')
    await page.getByRole('button', { name: 'Save text' }).tap()
    await expect(page.getByTestId('drawing-elements')).toContainText('Touch note')
  } finally { await context.close() }
})
